export class ApiError extends Error {
  readonly status: number;
  constructor(message: string, status: number, readonly code?: string) {
    super(message);
    this.name = 'ApiError';
    this.status = status;
  }
}

/** Transport boundary: a desktop shell can supply a different implementation via setTransport. */
export interface Transport {
  request<T>(method: string, path: string, body?: unknown, signal?: AbortSignal): Promise<T>;
}

const httpTransport: Transport = {
  async request<T>(method: string, path: string, body?: unknown, signal?: AbortSignal): Promise<T> {
    let res: Response;
    try {
      res = await fetch(`/api${path}`, {
        method,
        signal,
        headers: body === undefined ? undefined : { 'Content-Type': 'application/json' },
        body: body === undefined ? undefined : JSON.stringify(body),
      });
    } catch (e) {
      if (e instanceof DOMException && e.name === 'AbortError') throw e;
      throw new ApiError('Cannot reach the Skim server. Is it running?', 0);
    }
    const text = await res.text();
    let data: unknown = undefined;
    if (text) {
      try {
        data = JSON.parse(text);
      } catch {
        if (res.ok) throw new ApiError('Server returned a non-JSON response.', res.status);
      }
    }
    if (!res.ok) {
      const msg =
        data && typeof data === 'object' && 'error' in data && typeof (data as { error: unknown }).error === 'string'
          ? (data as { error: string }).error
          : `Request failed (HTTP ${res.status}).`;
      const code = data && typeof data === 'object' && 'code' in data && typeof data.code === 'string' ? data.code : undefined;
      throw new ApiError(msg, res.status, code);
    }
    return data as T;
  },
};

let transport: Transport = httpTransport;
export function setTransport(t: Transport): void {
  transport = t;
}

const req = <T>(method: string, path: string, body?: unknown, signal?: AbortSignal) =>
  transport.request<T>(method, path, body, signal);

export const api = {
  state: (signal?: AbortSignal) => req<AppState>('GET', '/state', undefined, signal),
  loadPullRequest: (url: string) => req<AppState>('POST', '/pull-request', { url }),
  inbox: (filter: { username?: string; repo?: string } = {}, signal?: AbortSignal) => {
    const q = new URLSearchParams();
    if (filter.username) q.set('username', filter.username);
    if (filter.repo) q.set('repo', filter.repo);
    const s = q.toString();
    return req<ReviewInbox>('GET', s ? `/inbox?${s}` : '/inbox', undefined, signal);
  },
  commits: (r: CommitRequest, signal?: AbortSignal) =>
    req<CommitList>('GET', `/commits?${new URLSearchParams({ prKey: r.prKey, baseSha: r.baseSha, headSha: r.headSha })}`, undefined, signal),
  analysis: (signal?: AbortSignal) => req<AnalysisUpdate>('GET', '/analysis', undefined, signal),
  refreshAnalysis: () => req<AnalysisUpdate>('POST', '/analysis', {}),
  review: () => req<AppState>('POST', '/review', {}),
  setReviewed: (r: CommitRequest & { paths: readonly string[]; reviewed: boolean }) =>
    req<FileReviewUpdate>('POST', '/reviewed', r),
  reviewProgress: (r: CommitRequest, signal?: AbortSignal) =>
    req<ReviewProgressUpdate>('GET', `/review/progress?${new URLSearchParams(r)}`, undefined, signal),
  reviewThreads: (r: CommitRequest, signal?: AbortSignal) =>
    req<PublishedThreads>('GET', `/review-comments?${new URLSearchParams(r)}`, undefined, signal),
  attachments: (r: CommitRequest) => req<Attachments>('GET', `/attachments?${new URLSearchParams(r)}`),
  replyToReviewThread: (r: ReviewReply) => req<PublishedComment>('POST', '/review-comments/replies', r),
  importStyle: (repo?: { owner: string; repo: string }) =>
    req<{ style: string; sampleCount: number }>('POST', '/style/import', repo ?? {}),
  saveStyle: (style: string) => req<{ style: string }>('PUT', '/style', { style }),
  createComment: (comment: ManualCommentRequest) => req<ReviewComment>('POST', '/comments', comment),
  patchComment: (id: string, patch: { body?: string; status?: 'pending' }) =>
    req<ReviewComment>('PATCH', `/comments/${encodeURIComponent(id)}`, patch),
  deleteComment: (id: string) => req<DeletedComment>('DELETE', `/comments/${encodeURIComponent(id)}`, {}),
  publish: (identity: CommitRequest, event: ReviewEvent, body?: string) =>
    req<AppState>('POST', '/publish', { ...identity, event, ...(body ? { body } : {}) }),
  chat: (message: string, threadId?: string) =>
    req<ChatThread>('POST', '/chat', threadId ? { message, threadId } : { message }),
  verify: (r: VerifyRequest) => req<VerificationAccepted>('POST', '/verify', r),
  verifications: (identity?: CommitRequest, signal?: AbortSignal) =>
    req<VerificationUpdate>('GET', identity ? `/verifications?${new URLSearchParams(identity)}` : '/verifications', undefined, signal),
  cancelVerification: (jobId: string, identity: CommitRequest) =>
    req<VerificationJob>('POST', `/verifications/${encodeURIComponent(jobId)}/cancel`, identity),
  settings: () => req<Settings>('GET', '/settings'),
  saveSettings: (s: Settings, providerKeys: ProviderKeyUpdate[] = []) => req<Settings>('PUT', '/settings', { ...s, providerKeys }),
  workspace: (signal?: AbortSignal) => req<WorkspaceUpdate>('GET', '/workspace', undefined, signal),
  removeCheckout: (r: FinishRequest) => req<AppState>('POST', '/review/finish', r),
  permissions: (signal?: AbortSignal) =>
    req<{ permissions: Permission[] }>('GET', '/permissions', undefined, signal),
  resolvePermission: (id: string, optionId: string) =>
    req<{ ok: true }>('POST', `/permissions/${encodeURIComponent(id)}`, { optionId }),
  host: () => req<{ desktop: boolean }>('GET', '/host'),
  openExternal: (url: string) => req<{ ok: true }>('POST', '/open-external', { url }),
};

export function errorMessage(e: unknown): string {
  return e instanceof Error ? e.message : String(e);
}
